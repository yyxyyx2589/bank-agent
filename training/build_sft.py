# -*- coding: utf-8 -*-
"""build_sft.py — 构造银行域 LoRA 训练数据（RAG 范式对齐版）。

为什么要有这一步（这是整个中间基线成不成立的关键）：

  eval.py 的 run_baseline_rag 推理时给模型的输入是

      system: 你是银行坐席知识助手。
      user:   基于知识片段回答：
              {检索到的知识片段}

              问题：{客户问题}

  如果直接拿「裸问题 → 答案」去微调（最常见的做法），LoRA 学到的是
  「看到问题就凭记忆作答」，训练时从来没见过「知识片段」这个东西。
  推理时突然塞给它一段上下文，它会当成噪音忽略掉，或者开头复述一遍
  片段里的别的内容 —— 也就是被训成了直答器，而不是阅读器。

  所以本脚本做的核心只有一件事：**把训练数据的 messages 组装成与推理
  完全一致的结构**，并且只对 assistant 回复算 loss（completion-only
  masking，prompt 段标 -100）。

数据来源与选择（刻意的设计决策，见下方「为什么不用结构化表」）：
  · 24 条知识库文档（db/init_chroma.py 的 KB_DOCUMENTS）
    每条配一份人工撰写的坐席标准答复 + 6 个自然问法 + 3 个关键词式问法
  · 行外拒答 / 闲聊兜底话术（约 40 条），上下文用**真实检索结果**，
    这样模型学到的是「片段不相关时该怎么办」

为什么不用结构化表（products / business_rules / tickets）：
  那三张表里的精确数字（7.20% / 20万 / 已解决）恰恰是**纯 RAG 检索不到、
  只有 Agent 调工具才能拿到的**。如果把这些答案也训进 LoRA，中间基线就会
  靠「背答案」虚高，三基线对比立刻被污染 —— 面试官一句「它这不是检索到的，
  是背下来的吧」就能把整张表推翻。
  所以这里刻意只喂知识库语料，让中间基线保持「有据可依，但边界就是知识库」。
  这个选择本身就是可讲的：为了对比干净，主动放弃了让自己基线上分的捷径。

数据泄漏防护：
  逐条剔除与 data/eval_questions.jsonl 完全相同的题（归一化后比对），
  保证训练集与评测集在「问题」层面不重叠。注意诚实边界：评测期望要点是
  知识库里的**事实**，事实层面的重合无法也**不应**避免 —— 避免它就等于
  要求模型不许知道业务知识。这一点在报告里如实标注。

输出：
  data/bank_sft_raw.jsonl   人类可读的 messages（用于人工复核训练数据）
  data/bank_sft.jsonl       预 tokenized 的 {input_ids, labels}（训练直接吃）

用法：
  python training/build_sft.py
"""
