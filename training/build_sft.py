def _norm(s: str) -> str:
    """与 eval.py 的 _norm 一致：去掉所有空白后比对。"""
    return re.sub(r"\s+", "", s or "")


def _sim(a: str, b: str) -> float:
    """字符级相似度（difflib 序列匹配比），用于近重复检测。"""
    return difflib.SequenceMatcher(None, a, b).ratio()


# 近重复闸门阈值。为什么不能只做「精确相同」这一道：
#   第一版实测——精确匹配剔除了 **0 条**，看着很干净，但实际上训练集里
#   「银行卡丢了要怎么补办呢」和评测题「银行卡丢了怎么补办」只差三个字。
#   这种近重复同样构成泄漏：模型不需要学会"读片段"，只要回忆训练时背下的
#   那句答案就能得分 —— 中间基线的分数会被虚高，三基线对比失去意义。
#   0.72 是在「挡住近重复」和「不误杀正常问法」之间取的：低于它的问法
#   已经需要模型真正理解片段才能答出来。
NEAR_DUP_THRESHOLD = 0.72


def load_eval_questions() -> set:
    """读评测题集合（用于泄漏防护）。"""
    if not EVAL_FILE.exists():
        return set()
    qs = set()
    for line in EVAL_FILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            qs.add(_norm(json.loads(line)["question"]))
    return qs


def make_context_for_extras(questions: list) -> dict:
    """对行外/闲聊问题跑真实检索，取回 top-1 片段作为上下文。"""
    from tools import TOOL_REGISTRY
    tool = TOOL_REGISTRY["search_knowledge"]
    ctx = {}
    for q in questions:
        try:
            raw = tool.call({"query": q, "top_k": 1})
            res = json.loads(raw).get("results") or []
            ctx[q] = res[0]["text"] if res else ""
        except Exception as e:  # 检索不可用不该让整个脚本挂掉
            print(f"  [!] 检索失败（{q[:14]}…）: {e}")
            ctx[q] = ""
    return ctx


def main():
    kb = {d["id"]: d for d in KB_DOCUMENTS}
    missing = [k for k in KB_QA if k not in kb]
    if missing:
        print(f"[!] KB_QA 引用了不存在的文档 id: {missing}")
        return

    eval_qs = load_eval_questions()
    print(f"[*] 评测题 {len(eval_qs)} 条，用作数据泄漏防护")

    # ---------- 组织 (question, answer, context) 三元组 ----------
    triples = []
    for kid, spec in KB_QA.items():
        ctx = kb[kid]["text"]
        for q in spec["questions"]:
            triples.append((q, spec["answer"], ctx))
        for kw in kb[kid]["keywords"][:KEYWORD_QUERIES_PER_DOC]:
            triples.append((kw, spec["answer"], ctx))
    print(f"[*] 知识库问答对: {len(triples)} 条"
          f"（{len(KB_QA)} 条 KB × 每题 {len(next(iter(KB_QA.values()))['questions'])} 问"
          f" + {KEYWORD_QUERIES_PER_DOC} 个关键词查询）")

    if EXTRA_USE_REAL_RETRIEVAL:
        extra_qs = [q for q, _ in EXTRA_QA]
        print(f"[*] 行外/闲聊 {len(extra_qs)} 条，跑真实检索取上下文 …")
        extra_ctx = make_context_for_extras(extra_qs)
    else:
        extra_ctx = {}
    for q, a in EXTRA_QA:
        triples.append((q, a, extra_ctx.get(q, "")))
    print(f"[*] 合计 {len(triples)} 条三元组（含行外/闲聊 {len(EXTRA_QA)} 条）")

    # ---------- 数据泄漏防护（两道闸门）----------
    # 闸门一：与评测题完全相同 → 剔除
    # 闸门二：与评测题字符相似度 ≥ NEAR_DUP_THRESHOLD → 剔除
    #         （只做闸门一是不够的，理由见 NEAR_DUP_THRESHOLD 处的说明）
    before = len(triples)
    dropped_exact, dropped_near, near_pairs = 0, 0, []
    kept = []
    for t in triples:
        q = _norm(t[0])
        if q in eval_qs:
            dropped_exact += 1
            continue
        worst, worst_q = 0.0, ""
        for e in eval_qs:
            r = _sim(q, e)
            if r > worst:
                worst, worst_q = r, e
        if worst >= NEAR_DUP_THRESHOLD:
            dropped_near += 1
            near_pairs.append((t[0], worst_q, round(worst, 3)))
            continue
        kept.append(t)
    triples = kept
    print(f"[*] 泄漏防护 · 闸门一（完全相同）：剔除 {dropped_exact} 条")
    print(f"[*] 泄漏防护 · 闸门二（相似度≥{NEAR_DUP_THRESHOLD}）：剔除 {dropped_near} 条 "
          f"→ 保留 {len(triples)} 条")
    for q, eq, r in near_pairs:
        print(f"      {r}  「{q}」 ≈ 评测题「{eq}」")

    # ---------- 组装 messages（与 run_baseline_rag 逐字同构）----------
    records = []
    for q, a, ctx in triples:
        user = RAG_USER_TMPL.format(context=ctx, question=q) if ctx else q
        records.append([
            {"role": "system", "content": RAG_SYSTEM},
            {"role": "user", "content": user},
            {"role": "assistant", "content": a},
        ])

    # 人类可读版（便于人工复核训练数据，也便于写进报告）
    with open(OUT_RAW, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps({"messages": r}, ensure_ascii=False) + "\n")
    print(f"[✓] 可读版已写入 {OUT_RAW}")

    # ---------- tokenize + completion-only loss mask ----------
    from transformers import AutoTokenizer
    tokenizer = AutoTokenizer.from_pretrained(MODEL_PATH, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    out, lens, too_long = [], [], 0
    for msgs in records:
        full_ids = tokenizer.apply_chat_template(
            msgs, tokenize=True, add_generation_prompt=False)
        prompt_ids = tokenizer.apply_chat_template(
            msgs[:2], tokenize=True, add_generation_prompt=True)
        if len(prompt_ids) >= len(full_ids):
            too_long += 1
            continue
        labels = [-100] * len(prompt_ids) + full_ids[len(prompt_ids):]
        out.append({"input_ids": full_ids, "labels": labels})
        lens.append(len(full_ids))

    with open(OUT_TOK, "w", encoding="utf-8") as f:
        for r in out:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    lens.sort()
    print("=" * 60)
    print(f"[✓] 预 tokenized 数据已写入 {OUT_TOK}")
    print(f"    样本 {len(out)} 条 | 过长跳过 {too_long} 条")
    if lens:
        p50 = lens[len(lens) // 2]
        p95 = lens[int(len(lens) * 0.95)]
        print(f"    token 长度: 最短 {lens[0]} / 中位 {p50} / p95 {p95} / 最长 {lens[-1]}")


if __name__ == "__main__":
    main()
