"""ChromaDB 向量库初始化脚本（银行远程银行坐席知识助手版）。

把知识库从「运维故障模式」替换为「银行个人/对公业务规则」，
向量检索链路（ChromaDB + sentence-transformers）与 ops-agent 完全一致。

embedding 模型：paraphrase-multilingual-MiniLM-L12-v2
  - 多语言含中文，模型 ~100MB
  - CPU 推理可接受（单次 embedding ~50ms）
  - 384 维向量
  - 需设 HF_HUB_OFFLINE=1 跳过 huggingface SSL 检查（模型已缓存）

ChromaDB 持久化：./data/chroma/（本地文件，重启不丢）
距离度量：collection 以 hnsw:space=cosine 建立，但 ChromaDB 返回的是
          「归一化后的 squared L2 距离」，不能直接写 sim = 1 - distance。
          验证查询与检索路径统一手算余弦相似度（见 tools/rag_search.py 的 _cosine_similarity）。

keywords 设计原则（决定 kw_coverage 的信噪比）：
  只放「坐席和客户实际会说的口语词」，每条控制在 5–7 个。
  早期版本每条放了 8–10 个偏书面的词，导致 kw_coverage 被稀释、
  高置信判定的 KW_COVERAGE_LOW 门槛失效 —— 精简后覆盖率才具备区分度。

知识库职责边界（决定路由走向）：
  知识库讲**规则**（怎么办、要什么、能不能），产品参数表讲**数字**（利率多少、费率多少）。
  两者边界不清时会出现一种隐蔽的错答：客户问"12 期手续费率是多少"，
  知识库命中率极高（sim 0.81）直接被 rag_direct 拿去作答，但它只能给出一个
  区间（"一般在 7%~9%"），而产品表里躺着精确值 7.20%。
  这个问题的解法不在知识库侧做减法，而在路由侧加判定 —— 见 router.py 的
  `_needs_live_data()`：问"具体数字"的问题即使高置信也强制走 Agent 查表。

数据说明：以下 24 条为通用业务规则整理，参照公开监管规定与行业通行做法编写，
         不涉及任何真实机构的专属政策，仅用于技术演示。

运行：python db/init_chroma.py
"""
