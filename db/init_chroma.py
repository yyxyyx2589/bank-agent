def main():
    import chromadb
    from sentence_transformers import SentenceTransformer

    chroma_path = str(Path(__file__).parent.parent / "data" / "chroma")
    print(f"ChromaDB 路径: {chroma_path}")

    print("加载 embedding 模型（paraphrase-multilingual-MiniLM-L12-v2）...")
    embed_model = SentenceTransformer("paraphrase-multilingual-MiniLM-L12-v2")
    print(f"模型加载完成，向量维度: {embed_model.get_embedding_dimension()}")

    client = chromadb.PersistentClient(path=chroma_path)

    try:
        client.delete_collection(COLLECTION_NAME)
        print(f"已删除旧 collection: {COLLECTION_NAME}")
    except Exception:
        pass

    # 创建 collection，用 cosine 距离
    collection = client.create_collection(
        name=COLLECTION_NAME,
        metadata={"description": "银行远程银行坐席业务知识库"},
        configuration={"hnsw:space": "cosine"})

    print(f"开始 embedding {len(KB_DOCUMENTS)} 条知识...")
    texts = [doc["text"] for doc in KB_DOCUMENTS]
    embeddings = embed_model.encode(texts).tolist()

    collection.add(
        ids=[doc["id"] for doc in KB_DOCUMENTS],
        documents=texts,
        embeddings=embeddings,
        metadatas=[{"keywords": ",".join(doc["keywords"])} for doc in KB_DOCUMENTS],
    )
    print(f"插入完成，collection 现有 {collection.count()} 条")

    # 验证查询（用 query_embeddings，不用 query_texts 避免 ChromaDB 内部重复 embedding）
    print("\n=== 验证查询（cosine 相似度）===")
    test_queries = [
        ("开卡需要带什么材料", "kb-001"),
        ("手机银行转账一天最多能转多少", "kb-005"),
        ("信用卡分期手续费怎么算", "kb-008"),
        ("理财产品 R3 是什么意思", "kb-016"),
        ("我的账户为什么被冻结了", "kb-021"),
        ("企业网银转账要几个人审批", "kb-020"),
        ("房贷提前还款有违约金吗", "kb-013"),
        ("征信报告有错误怎么改", "kb-023"),
        ("未成年人能自己开卡吗", "kb-002"),
        ("银行卡丢了怎么补办", "kb-003"),
        ("定期存款提前取出来利息怎么算", "kb-014"),
        ("大额存单起存多少钱", "kb-015"),
        ("跨行转账手续费多少", "kb-007"),
        ("企业开基本户要什么材料", "kb-019"),
        ("收到诈骗电话账户被冻结怎么办", "kb-022"),
        ("代发工资一般多久到账", "kb-024"),
    ]
    hit = 0
    for q, expect in test_queries:
        q_emb = embed_model.encode([q]).tolist()
        results = collection.query(
            query_embeddings=q_emb,
            n_results=1,
            include=["documents", "distances", "embeddings"])
        top_id = results["ids"][0][0]
        # 注意：hnsw:space=cosine 下 ChromaDB 返回的是「归一化后的 squared L2 距离」，
        # 不是标准 cosine distance —— 直接写 1 - dist 会算出负数。这里手算余弦相似度，
        # 与 tools/rag_search.py 的 _cosine_similarity 保持一致。
        qv = np.asarray(q_emb[0], dtype=float)
        kv = np.asarray(results["embeddings"][0][0], dtype=float)
        sim = float(np.dot(qv, kv) / (np.linalg.norm(qv) * np.linalg.norm(kv)))
        ok = top_id == expect
        hit += 1 if ok else 0
        print(f"  {'OK  ' if ok else 'MISS'} q={q:26} top={top_id}(期望{expect}) sim={sim:.3f}")

    print(f"\n纯向量 top1 命中率: {hit}/{len(test_queries)}")
    print(f"ChromaDB 初始化完成: {chroma_path}")


if __name__ == "__main__":
    main()
